/**
 * Pentest — Finding NEW-NODE-MODULES (HIGH): node_modules directory is not restricted
 * 
 * Similar to .venv, the node_modules directory can contain sensitive information
 * and should be restricted to prevent unauthorized access.
 * 
 * Secure expectation: node_modules directories should be restricted like .git and .venv directories.
 * These tests verify that the fixes are working correctly.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import * as path from "node:path";
import { Sandbox, SandboxError } from "../../src/sandbox/sandbox.ts";
import { writeFile, readFile } from "../../src/tools/write.ts";
import { makeFixture, cleanupFixture } from "../fixtures.ts";
import { isRestricted } from "../../src/sandbox/policy.ts";

