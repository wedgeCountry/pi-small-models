test("NEW-NODE-MODULES-4: Sandbox should block write to node_modules/hello_world", async (t) => {
  const root = await makeFixture({ "src/index.ts": "export const x = 1;" });
  t.after(() => cleanupFixture(root));

  const sb = new Sandbox(root);

  // This should throw SandboxError with reason "restricted"
  await assert.rejects(
    async () => await writeFile(sb, "node_modules/hello_world", "hello world"),
    (err: unknown) => {
      return err instanceof SandboxError && err.reason === "restricted";
    },
    "SECURITY: writeFile to node_modules/hello_world should be blocked"
  );
});

